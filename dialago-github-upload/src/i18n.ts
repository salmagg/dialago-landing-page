export function getInitialLang(): Lang {
  const stored = localStorage.getItem('dialago-lang');
  if (stored === 'en' || stored === 'es') return stored;
  const navLang = navigator.language?.toLowerCase() ?? 'en';
  return navLang.startsWith('es') ? 'es' : 'en';
}

export function t(lang: Lang, key: string, vars?: Record<string, string>): string {
  let value =
    STRINGS[lang][key] ??
    PRACTICE_ANALYSIS_STRINGS[lang][key as keyof (typeof PRACTICE_ANALYSIS_STRINGS)['en']] ??
    FLASHCARD_STRINGS[lang][key] ??
    STRINGS.en[key] ??
    PRACTICE_ANALYSIS_STRINGS.en[key as keyof (typeof PRACTICE_ANALYSIS_STRINGS)['en']] ??
    FLASHCARD_STRINGS.en[key] ??
    key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, replacement);
    }
  }
  return value;
}
